/**
 * Capture what a BASE tree outputs for every case of the output-equivalence corpus, as one SHA-256
 * per case, committed as expectation data in `test/__data__/output-digests.json`.
 *
 *     pnpm exec vitest run --config test/support/capture.config.ts
 *
 * It captures against `origin/main`, or against the ref in `CAPTURE_BASE` when that is set. It runs
 * under Vitest, with its own config, so the base tree's TypeScript loads the way the tests load
 * head's, and `pnpm test` never runs it.
 *
 * The corpus and the record of one case live in `test/support/output-corpus.ts`, shared with
 * `test/output-equivalence.test.ts`, which recomputes each digest on head and requires it to be
 * identical. That is the evidence a change meant to make validation or conversion faster changed no
 * result, issue, error or returned Temporal value.
 *
 * The cases are built with head's own corpus code and only `src/` comes from the base ref, so both
 * sides convert exactly the same values. `git archive` is used rather than a worktree, so the
 * materialized tree cannot pick up an untracked file. The tree is written under `.tmp/` inside the
 * package, so its `temporal-polyfill` import resolves to this package's own dependency. Re-run it
 * at the same base and the file comes back byte-identical.
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { expect, it } from "vitest";

import { digestOf, outputCorpus, recordOf, type OutputApi } from "./output-corpus.js";
import { packageRoot, scratchDir } from "./paths.js";

const OUT = path.join(packageRoot, "test", "__data__", "output-digests.json");

/** Materialize `src/` at `ref` under `.tmp/` and import it. */
async function loadBase(ref: string): Promise<{ api: OutputApi; dir: string }> {
  mkdirSync(scratchDir, { recursive: true });
  const dir = mkdtempSync(path.join(scratchDir, "output-digests-"));
  const archive = execFileSync("git", ["archive", ref, "src"], {
    cwd: packageRoot,
    maxBuffer: 64 * 1024 * 1024,
    encoding: "buffer",
  });
  execFileSync("tar", ["-x", "-C", dir], { input: archive });
  const api = (await import(pathToFileURL(path.join(dir, "src", "index.ts")).href)) as OutputApi;
  return { api, dir };
}

it("captures the base tree's output digests", async () => {
  const ref = process.env["CAPTURE_BASE"] ?? "origin/main";
  const sha = execFileSync("git", ["rev-parse", ref], {
    cwd: packageRoot,
    encoding: "utf8",
  }).trim();
  const { api, dir } = await loadBase(ref);
  try {
    const cases: Record<string, string> = {};
    for (const c of outputCorpus()) {
      expect(c.name in cases, `two corpus cases are named ${c.name}`).toBe(false);
      cases[c.name] = digestOf(recordOf(api, c));
    }
    const payload = {
      note: "Generated by test/support/capture-output-digests.ts. Do not hand-edit: re-run it instead.",
      base: sha,
      cases,
    };
    mkdirSync(path.dirname(OUT), { recursive: true });
    writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
